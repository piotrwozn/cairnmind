"""Universal MCP client preset generator and safe JSON/JSONC/TOML deep-merge engine.

Guarantees:
- Never adds auto-approval or consent-bypassing flags (`autoApprove`, `alwaysAllow`,
  `enableAllProjectMcpServers`, `trust`, etc.).
- Deep-merges only the Cairnmind server key, preserving all sibling MCP servers and
  unrelated client settings.
- Resolves absolute executable paths so GUI apps without shell PATH inheritance can
  launch Cairnmind reliably, warning if the executable lives in a temporary directory.
- Protects multi-project global (`--scope user`) configs from silently overwriting a
  different repository's `cairnmind` entry.
- Backs up modified files to `<file>.cairnmind.bak` and writes atomically (`os.replace`).
"""
