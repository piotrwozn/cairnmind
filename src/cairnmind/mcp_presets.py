def validate_server_name(name: str) -> str:
    if not isinstance(name, str) or not _SERVER_NAME_RE.fullmatch(name):
        raise ValueError(
            f"Invalid MCP server name {name!r}: must start with a letter or digit and use only "
            "letters, digits, '.', '_' or '-' (max 64 characters)."
        )
    return name


def suggest_server_name(project_root: Path) -> str:
    slug = re.sub(r"[^A-Za-z0-9_-]+", "-", project_root.name).strip("-").lower()
    slug = (slug or "project")[:48]
    return f"cairnmind-{slug}"


def strip_jsonc(text: str) -> str:
    """Strip // and /* */ comments and trailing commas from JSONC while preserving string literals."""
    out: list[str] = []
    n = len(text)
    i = 0
    in_string = False
    escaped = False

    while i < n:
        ch = text[i]
        if in_string:
            out.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            i += 1
            continue

        if ch == '"':
            in_string = True
            out.append(ch)
            i += 1
            continue

        if ch == "/" and i + 1 < n:
            nxt = text[i + 1]
            if nxt == "/":
                i += 2
                while i < n and text[i] not in ("\n", "\r"):
                    i += 1
                continue
            if nxt == "*":
                i += 2
                closed = False
                while i + 1 < n:
                    if text[i] == "*" and text[i + 1] == "/":
                        i += 2
                        closed = True
                        break
                    if text[i] == "\n":
                        out.append("\n")
                    i += 1
                if not closed:
                    raise ConfigSyntaxError("Unterminated /* block comment in JSONC.")
                continue

        out.append(ch)
        i += 1

    no_comments = "".join(out)

    # Remove trailing commas before '}' or ']' outside string literals.
    cleaned: list[str] = []
    m = len(no_comments)
    j = 0
    in_string = False
    escaped = False
    while j < m:
        ch = no_comments[j]
        if in_string:
            cleaned.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            j += 1
            continue
        if ch == '"':
            in_string = True
            cleaned.append(ch)
            j += 1
            continue
        if ch == ",":
            k = j + 1
            while k < m and no_comments[k] in (" ", "\t", "\r", "\n"):
                k += 1
            if k < m and no_comments[k] in ("}", "]"):
                # Skip trailing comma; preserve any intervening whitespace/newlines.
                j += 1
                continue
        cleaned.append(ch)
        j += 1
    return "".join(cleaned)


def parse_json_or_jsonc(text: str, path: Path | str = "<config>", *, allow_jsonc: bool = True) -> dict[str, Any]:
    """Parse JSON or JSONC safely into a dict; never silently ignores malformed files."""
    if not text.strip():
        return {}
    stripped = text.lstrip("\ufeff")
    try:
        candidate = strip_jsonc(stripped) if allow_jsonc else stripped
        data = json.loads(candidate)
    except (ValueError, ConfigSyntaxError) as exc:
        raise ConfigSyntaxError(f"Cannot parse {path}: {exc}. Original file left unchanged.") from exc
    if not isinstance(data, dict):
        raise ConfigSyntaxError(f"Expected a JSON object at top level of {path}; original file left unchanged.")
    return data


def _platform_name(system: str | None = None) -> str:
    raw = (system or sys.platform).lower()
    if raw.startswith("darwin"):
        return "darwin"
    if raw.startswith("win"):
        return "win32"
    return "linux"


def _appdata_dir(home: Path, env: dict[str, str], plat: str) -> Path:
    if plat == "win32":
        raw = env.get("APPDATA")
        if raw:
            return Path(raw)
        return home / "AppData" / "Roaming"
    if plat == "darwin":
        return home / "Library" / "Application Support"
    xdg = env.get("XDG_CONFIG_HOME")
    return Path(xdg) if xdg else home / ".config"


def config_path_for_client(
    client: str,
    scope: str,
    project_root: Path,
    *,
    home: Path | None = None,
    env: dict[str, str] | None = None,
    system: str | None = None,
) -> Path | None:
    """Resolve the target config file path for `(client, scope)`, or None for stdout-only (`generic`)."""
    if client not in CLIENT_SPECS:
        raise ValueError(f"Unsupported MCP client: {client!r}. Supported: {', '.join(SUPPORTED_CLIENTS)}")
    spec = CLIENT_SPECS[client]
    if client == "generic" or scope == "stdout":
        return None
    if scope == "project" and not spec.supports_project:
        raise ValueError(
            f"Client {client!r} does not have a project-scoped MCP config; use `--scope user`."
        )
    if scope == "user" and not spec.supports_user:
        raise ValueError(f"Client {client!r} does not have a user-scoped MCP config.")

    root = project_root.expanduser().resolve()
    home_dir = (home or Path.home()).expanduser()
    environ = dict(os.environ if env is None else env)
    plat = _platform_name(system)
    appdata = _appdata_dir(home_dir, environ, plat)

    if scope == "project":
        project_paths = {
            "claude-code": root / ".mcp.json",
            "cursor": root / ".cursor" / "mcp.json",
            "vscode": root / ".vscode" / "mcp.json",
            "roo-code": root / ".roo" / "mcp.json",
            "codex": root / ".codex" / "config.toml",
            "gemini-cli": root / ".gemini" / "settings.json",
            "zed": root / ".zed" / "settings.json",
        }
        return project_paths[client]

    # User / global scope paths.
    code_user = appdata / "Code" / "User"
    user_paths = {
        "claude-code": home_dir / ".claude.json",
        "claude-desktop": appdata / "Claude" / "claude_desktop_config.json",
        "cursor": home_dir / ".cursor" / "mcp.json",
        "windsurf": home_dir / ".codeium" / "windsurf" / "mcp_config.json",
        "vscode": code_user / "mcp.json",
        "cline": code_user / "globalStorage" / "saoudrizwan.claude-dev" / "settings" / "cline_mcp_settings.json",
        "roo-code": code_user / "globalStorage" / "rooveterinaryinc.roo-cline" / "settings" / "mcp_settings.json",
        "codex": home_dir / ".codex" / "config.toml",
        "gemini-cli": home_dir / ".gemini" / "settings.json",
        "zed": (appdata / "Zed" / "settings.json") if plat == "win32" else (home_dir / ".config" / "zed" / "settings.json"),
    }
    return user_paths[client]


def _is_temp_path(path: Path) -> bool:
    """Whether an executable path resides in a temporary directory."""
    resolved = str(path).replace("\\", "/")
    temp_roots = [str(Path(tempfile.gettempdir()).resolve()).replace("\\", "/"), "/tmp", "/var/tmp", "/private/var/folders"]
    lower = resolved.lower()
    for base in temp_roots:
        norm_base = base.rstrip("/").lower()
        if norm_base and (lower == norm_base or lower.startswith(norm_base + "/")):
            return True
    return "/temp/" in lower or "/tmp/" in lower


def resolve_executable(executable: str | None = None) -> tuple[str, list[str]]:
    """Resolve an absolute executable path for GUI MCP clients; warn if inside a temp directory.

    Preserves virtualenv symlinks (e.g. `.venv/bin/python`) instead of dereferencing them to the
    base system interpreter, which would lose `pyvenv.cfg` and fail to import `cairnmind`.
    """
    warnings: list[str] = []
    chosen = executable or sys.executable
    if re.match(r"^[A-Za-z]:[\\/]", chosen):
        if _is_temp_path(Path(chosen.replace("\\", "/"))):
            warnings.append(
                f"Resolved executable {chosen} is inside a temporary directory; "
                "GUI clients may fail after cleanup or reboot. Install Cairnmind into a permanent location."
            )
        return chosen, warnings
    path = Path(chosen).expanduser()
    if not path.is_absolute():
        found = shutil.which(chosen)
        if found:
            path = Path(found)
    resolved = Path(os.path.abspath(path))
    if not resolved.is_absolute():
        warnings.append(f"Executable path {resolved} is not absolute; GUI MCP clients may fail to start it.")
    if _is_temp_path(resolved):
        warnings.append(
            f"Resolved executable {resolved} is inside a temporary directory; "
            "GUI clients may fail after cleanup or reboot. Install Cairnmind into a permanent location."
        )
    return str(resolved), warnings


def build_server_entry(
    client: str,
    settings: Settings,
    project_root: Path,
    *,
    scope: str,
    worktree: Path | None = None,
    external: bool = False,
    executable: str | None = None,
) -> tuple[dict[str, Any], list[str]]:
    """Build the client-specific MCP server configuration entry (never with consent-bypass keys)."""
    spec = CLIENT_SPECS[client]
    command, warnings = resolve_executable(executable)
    project_str = str(project_root.expanduser().resolve())
    data_dir_str = str(settings.data_dir.expanduser().resolve())
    use_native = spec.native_project_mode and scope == "project" and not external

    base_args = ["-I", "-m", "cairnmind", "--data-dir", data_dir_str, "mcp"]
    if not use_native:
        base_args.extend(["--client", "external", "--project", project_str])
        if worktree is not None:
            base_args.extend(["--worktree", str(worktree.expanduser().resolve())])

    if client == "vscode":
        entry: dict[str, Any] = {"type": "stdio", "command": command, "args": base_args}
    elif client == "zed":
        entry = {"command": command, "args": base_args, "env": {}}
    elif client == "codex":
        entry = {
            "command": command,
            "args": base_args,
            "startup_timeout_sec": 15,
            "tool_timeout_sec": codex_tool_timeout(settings),
        }
        if use_native:
            entry["env_vars"] = list(SESSION_ENV_VARS)
    elif client == "claude-code" and use_native:
        entry = {
            "command": command,
            "args": base_args,
            "env": {name: "${" + name + ":-}" for name in SESSION_ENV_VARS},
        }
    else:
        entry = {"command": command, "args": base_args}

    # Belt-and-suspenders invariant: never emit any consent-bypass key.
    assert not (FORBIDDEN_CONSENT_KEYS & set(entry.keys())), f"Forbidden consent keys in preset for {client}"
    return entry, warnings


def _is_cairnmind_entry(entry: Any) -> bool:
    """Whether an existing MCP server config entry belongs to Cairnmind (or earlier DevBrain)."""
    if not isinstance(entry, dict):
        return False
    cmd = entry.get("command")
    args = entry.get("args")
    if isinstance(cmd, dict):
        # Support older Zed nested command object if encountered.
        args = cmd.get("args")
        cmd = cmd.get("path")
    if isinstance(cmd, str) and Path(cmd).name.lower() in ("cairnmind", "cairnmind.exe", "devbrain", "devbrain.exe"):
        return True
    if isinstance(args, list):
        for idx in range(len(args) - 1):
            if args[idx] == "-m" and args[idx + 1] in ("cairnmind", "devbrain"):
                return True
        if any(isinstance(a, str) and Path(a).name.lower() in ("cairnmind", "devbrain") for a in args):
            return True
    return False


def _entry_project_path(entry: Any) -> str | None:
    """Extract `--project <value>` from an existing Cairnmind entry, if present."""
    if not isinstance(entry, dict):
        return None
    args = entry.get("args")
    if isinstance(entry.get("command"), dict):
        args = entry["command"].get("args")
    if not isinstance(args, list):
        return None
    for idx, item in enumerate(args):
        if item == "--project" and idx + 1 < len(args) and isinstance(args[idx + 1], str):
            return args[idx + 1]
        if isinstance(item, str) and item.startswith("--project="):
            return item.split("=", 1)[1]
    return None


def _check_entry_conflicts(
    existing: Any,
    *,
    server_name: str,
    scope: str,
    project_root: Path,
    path: Path | str,
    force: bool,
) -> None:
    if existing is None:
        return
    if not _is_cairnmind_entry(existing):
        suggested = suggest_server_name(project_root)
        raise ForeignServerConflictError(
            f"An unrelated MCP server already owns {server_name!r} in {path}; original file left unchanged. "
            f"Pass `--name {suggested}` to keep both."
        )
    if scope == "user" and not force:
        prev_project = _entry_project_path(existing)
        target_project = str(project_root.expanduser().resolve())
        if prev_project:
            try:
                prev_norm = str(Path(prev_project).expanduser().resolve())
            except OSError:
                prev_norm = prev_project
            if prev_norm != target_project:
                suggested = suggest_server_name(project_root)
                raise MultiProjectConflictError(
                    f"Global config {path} already binds {server_name!r} to another project ({prev_project}). "
                    f"Refusing to overwrite it silently; use `--name {suggested}` for this project "
                    "or pass `--force` to replace it."
                )


def merge_json_document(
    original_text: str,
    *,
    root_key: str,
    server_name: str,
    entry: dict[str, Any],
    scope: str,
    project_root: Path,
    path: Path | str,
    allow_jsonc: bool = True,
    force: bool = False,
) -> str:
    """Deep-merge `entry` into JSON/JSONC text under `root_key[server_name]` without touching other keys."""
    doc = parse_json_or_jsonc(original_text, path, allow_jsonc=allow_jsonc)
    container = doc.get(root_key)
    if container is None:
        container = {}
        doc[root_key] = container
    if not isinstance(container, dict):
        raise ConfigSyntaxError(f"Expected {root_key!r} to be a JSON object in {path}; original file left unchanged.")
    existing = container.get(server_name)
    _check_entry_conflicts(
        existing,
        server_name=server_name,
        scope=scope,
        project_root=project_root,
        path=path,
        force=force,
    )
    merged_servers: dict[str, Any] = {}
    inserted = False
    for key, val in container.items():
        if key == server_name:
            merged_servers[server_name] = entry
            inserted = True
        elif server_name == SERVER and key == EARLIER_SERVER and _is_cairnmind_entry(val) and SERVER not in container:
            merged_servers[SERVER] = entry
            inserted = True
        else:
            merged_servers[key] = val
    if not inserted:
        merged_servers[server_name] = entry
    doc[root_key] = merged_servers
    rendered = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"
    # Validate output is strict valid JSON.
    json.loads(rendered)
    return rendered


def merge_toml_document(
    original_text: str,
    *,
    root_key: str,
    server_name: str,
    entry: dict[str, Any],
    scope: str,
    project_root: Path,
    path: Path | str,
    force: bool = False,
) -> str:
    """Deep-merge `entry` into TOML text under `[mcp_servers.<server_name>]` preserving comments & siblings."""
    try:
        parsed = tomllib.loads(original_text) if original_text.strip() else {}
    except tomllib.TOMLDecodeError as exc:
        raise ConfigSyntaxError(f"Cannot parse TOML in {path}: {exc}. Original file left unchanged.") from exc

    servers = parsed.get(root_key, {})
    if servers is not None and not isinstance(servers, dict):
        raise ConfigSyntaxError(f"Expected [{root_key}] to be a TOML table in {path}; original file left unchanged.")
    existing = servers.get(server_name) if isinstance(servers, dict) else None
    if existing is not None and not isinstance(existing, dict):
        raise ConfigSyntaxError(
            f"Expected [{root_key}.{server_name}] to be a TOML table in {path}; original file left unchanged."
        )
    _check_entry_conflicts(
        existing,
        server_name=server_name,
        scope=scope,
        project_root=project_root,
        path=path,
        force=force,
    )

    if not original_text.strip():
        doc = tomlkit.document()
        if scope == "project" and server_name == SERVER:
            doc.add(tomlkit.comment(TOML_BEGIN.lstrip("# ")))
        parent = tomlkit.table(is_super_table=True)
        table = tomlkit.table()
        for field, value in entry.items():
            table[field] = value
        parent[server_name] = table
        doc[root_key] = parent
        if scope == "project" and server_name == SERVER:
            doc.add(tomlkit.comment(TOML_END.lstrip("# ")))
        rendered = tomlkit.dumps(doc)
        if not rendered.endswith("\n"):
            rendered += "\n"
        tomllib.loads(rendered)
        return rendered

    doc = tomlkit.parse(original_text)
    if root_key not in doc:
        parent = tomlkit.table(is_super_table=True)
        table = tomlkit.table()
        for field, value in entry.items():
            table[field] = value
        parent[server_name] = table
        doc[root_key] = parent
    else:
        parent = doc[root_key]
        if server_name in parent:
            table = parent[server_name]
            for field, value in entry.items():
                table[field] = value
            # Remove stale env_vars only if switching from native to external mode explicitly.
            if "env_vars" not in entry and "env_vars" in table and scope == "user":
                del table["env_vars"]
        else:
            table = tomlkit.table()
            for field, value in entry.items():
                table[field] = value
            parent[server_name] = table

    rendered = tomlkit.dumps(doc)
    if not rendered.endswith("\n"):
        rendered += "\n"
    # Validate output with stdlib tomllib before returning.
    tomllib.loads(rendered)
    return rendered


def atomic_write_with_backup(path: Path, text: str, *, new_mode: int = 0o600) -> tuple[bool, Path | None]:
    """Back up existing file to `<file>.cairnmind.bak` and atomically write `text` via `private_files`."""
    previous = path.read_bytes() if path.exists() else None
    encoded = text.encode("utf-8")
    if previous == encoded:
        return False, None

    previous_mode = stat.S_IMODE(path.stat().st_mode) if previous is not None else None
    path.parent.mkdir(parents=True, exist_ok=True)
    backup_path: Path | None = None
    if previous is not None:
        backup_path = path.with_name(f"{path.name}.cairnmind.bak")
        shutil.copy2(path, backup_path)

    mode = previous_mode if previous_mode is not None else new_mode
    private_files.write_durable_private(path, encoded, mode=mode, prefix=f".{path.name}.cairnmind-")
    return True, backup_path


def generate_preset(
    client: str,
    settings: Settings,
    project_root: Path,
    *,
    scope: str | None = None,
    server_name: str = SERVER,
    worktree: Path | None = None,
    external: bool = False,
    write: bool = False,
    force: bool = False,
    executable: str | None = None,
    home: Path | None = None,
    env: dict[str, str] | None = None,
    system: str | None = None,
) -> dict[str, Any]:
    """Generate (and optionally merge & atomically write) an MCP preset for `client`."""
    if client not in CLIENT_SPECS:
        raise ValueError(f"Unsupported MCP client: {client!r}. Supported: {', '.join(SUPPORTED_CLIENTS)}")
    validate_server_name(server_name)
    spec = CLIENT_SPECS[client]
    resolved_scope = scope or spec.default_scope
    if resolved_scope not in ("project", "user", "stdout"):
        raise ValueError("`--scope` must be 'project' or 'user'.")
    if client == "generic" and write:
        raise ValueError("Client 'generic' prints canonical JSON to stdout only and cannot be used with --write.")

    target_path = config_path_for_client(
        client,
        resolved_scope,
        project_root,
        home=home,
        env=env,
        system=system,
    )
    entry, warnings = build_server_entry(
        client,
        settings,
        project_root,
        scope=resolved_scope,
        worktree=worktree,
        external=external,
        executable=executable,
    )

    if target_path is None:
        rendered = json.dumps({spec.root_key: {server_name: entry}}, indent=2, ensure_ascii=False) + "\n"
        return {
            "client": client,
            "title": spec.title,
            "scope": "stdout",
            "format": spec.file_format,
            "root_key": spec.root_key,
            "server_name": server_name,
            "path": None,
            "entry": entry,
            "content": rendered,
            "diff": "",
            "changed": False,
            "written": False,
            "backup": None,
            "warnings": warnings,
        }

    original_text = target_path.read_text(encoding="utf-8") if target_path.exists() else ""
    if spec.file_format == "toml":
        merged_text = merge_toml_document(
            original_text,
            root_key=spec.root_key,
            server_name=server_name,
            entry=entry,
            scope=resolved_scope,
            project_root=project_root,
            path=target_path,
            force=force,
        )
    else:
        merged_text = merge_json_document(
            original_text,
            root_key=spec.root_key,
            server_name=server_name,
            entry=entry,
            scope=resolved_scope,
            project_root=project_root,
            path=target_path,
            allow_jsonc=(spec.file_format == "jsonc"),
            force=force,
        )

    diff = "".join(
        difflib.unified_diff(
            original_text.splitlines(keepends=True),
            merged_text.splitlines(keepends=True),
            fromfile=f"a/{target_path.name}",
            tofile=f"b/{target_path.name}",
        )
    )

    written = False
    changed = original_text != merged_text
    backup_path: Path | None = None
    if write:
        written, backup_path = atomic_write_with_backup(target_path, merged_text)
        changed = written

    return {
        "client": client,
        "title": spec.title,
        "scope": resolved_scope,
        "format": spec.file_format,
        "root_key": spec.root_key,
        "server_name": server_name,
        "path": str(target_path),
        "entry": entry,
        "content": merged_text,
        "diff": diff,
        "changed": changed,
        "written": written,
        "backup": str(backup_path) if backup_path else None,
        "warnings": warnings,
    }


def detect_installed_clients(
    project_root: Path,
    *,
    home: Path | None = None,
    env: dict[str, str] | None = None,
    system: str | None = None,
) -> list[dict[str, Any]]:
    """Detect installed MCP clients on the machine or configured in the repository (read-only)."""
    root = project_root.expanduser().resolve()
    home_dir = (home or Path.home()).expanduser()
    environ = dict(os.environ if env is None else env)
    path_var = environ.get("PATH", os.defpath)
    plat = _platform_name(system)
    appdata = _appdata_dir(home_dir, environ, plat)
    code_user = appdata / "Code" / "User"

    checks: list[tuple[str, str | None, list[Path]]] = [
        ("claude-code", "claude", [root / ".mcp.json", root / ".claude", home_dir / ".claude.json"]),
        ("claude-desktop", None, [appdata / "Claude"]),
        ("cursor", "cursor", [root / ".cursor", home_dir / ".cursor"]),
        ("windsurf", "windsurf", [home_dir / ".codeium" / "windsurf"]),
        ("vscode", "code", [root / ".vscode", code_user]),
        ("cline", None, [code_user / "globalStorage" / "saoudrizwan.claude-dev"]),
        ("roo-code", None, [root / ".roo", code_user / "globalStorage" / "rooveterinaryinc.roo-cline"]),
        ("codex", "codex", [root / ".codex", home_dir / ".codex"]),
        ("gemini-cli", "gemini", [root / ".gemini", home_dir / ".gemini"]),
        ("zed", "zed", [root / ".zed", (appdata / "Zed") if plat == "win32" else (home_dir / ".config" / "zed")]),
    ]

    detected: list[dict[str, Any]] = []
    for name, binary, markers in checks:
        found_bin = shutil.which(binary, path=path_var) if binary else None
        found_markers = [str(p) for p in markers if p.exists()]
        if found_bin or found_markers:
            spec = CLIENT_SPECS[name]
            detected.append({
                "client": name,
                "title": spec.title,
                "default_scope": spec.default_scope,
                "binary": found_bin,
                "markers": found_markers,
            })
    return detected


def discover_configured_presets(
    project_root: Path | None = None,
    *,
    home: Path | None = None,
    env: dict[str, str] | None = None,
    system: str | None = None,
) -> list[dict[str, Any]]:
    """Read-only scan of project and user config files for configured Cairnmind MCP presets."""
    found: list[dict[str, Any]] = []
    seen_paths: set[str] = set()
    base = (project_root or Path.cwd()).expanduser().resolve()

    for name, spec in CLIENT_SPECS.items():
        if name == "generic":
            continue
        scopes: list[str] = []
        if spec.supports_project and project_root is not None:
            scopes.append("project")
        if spec.supports_user:
            scopes.append("user")
        for scope in scopes:
            path = config_path_for_client(name, scope, base, home=home, env=env, system=system)
            if path is None or not path.is_file():
                continue
            key_path = f"{name}:{scope}:{path}"
            if key_path in seen_paths:
                continue
            seen_paths.add(key_path)
            entry_info = _inspect_preset_file(path, spec)
            if entry_info is not None:
                found.append({
                    "client": name,
                    "title": spec.title,
                    "scope": scope,
                    "path": str(path),
                    **entry_info,
                })
    return found


def _inspect_preset_file(path: Path, spec: ClientSpec) -> dict[str, Any] | None:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    try:
        if spec.file_format == "toml":
            doc = tomllib.loads(text) if text.strip() else {}
        else:
            doc = parse_json_or_jsonc(text, path, allow_jsonc=(spec.file_format == "jsonc"))
    except (ValueError, ConfigSyntaxError) as exc:
        return {"configured": False, "error": str(exc)}
    container = doc.get(spec.root_key)
    if not isinstance(container, dict):
        return None
    matches: list[dict[str, Any]] = []
    for srv_name, srv_val in container.items():
        if _is_cairnmind_entry(srv_val):
            consent_flags = sorted(FORBIDDEN_CONSENT_KEYS & set(srv_val.keys())) if isinstance(srv_val, dict) else []
            matches.append({
                "server_name": srv_name,
                "command": srv_val.get("command") if isinstance(srv_val, dict) else None,
                "args": srv_val.get("args") if isinstance(srv_val, dict) else None,
                "project": _entry_project_path(srv_val),
                "consent_flags": consent_flags,
            })
    if not matches:
        return None
    first = matches[0]
    return {
        "configured": True,
        "server_name": first["server_name"],
        "servers": matches,
        "project": first["project"],
        "consent_flags": [f for m in matches for f in m["consent_flags"]],
    }
